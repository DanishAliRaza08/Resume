// Embeds prisma/migrations/*/migration.sql into src/lib/server/migrations.generated.ts so the app can
// create its tables on start-up without the Prisma CLI (some hosts don't ship it at run time).
// Runs automatically before `npm run build`.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "prisma", "migrations");
const migrations = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(path.join(dir, d.name, "migration.sql")))
  .map((d) => d.name)
  .sort()
  .map((name) => {
    const sql = readFileSync(path.join(dir, name, "migration.sql"), "utf8");
    return { name, checksum: createHash("sha256").update(sql).digest("hex"), sql };
  });
const out =
  "// GENERATED by scripts/gen-migrations.mjs from prisma/migrations. Do not edit.\n" +
  "export const MIGRATIONS: { name: string; checksum: string; sql: string }[] = " +
  JSON.stringify(migrations, null, 2) +
  ";\n";
writeFileSync(path.join(process.cwd(), "src", "lib", "server", "migrations.generated.ts"), out);
console.log(`Embedded ${migrations.length} migration(s).`);
